-- significativement d'une spe a l'autre.
--
-- Les identifiants sont resolus contre item_template a l'import. Un identifiant
-- absent de la base n'est pas insere, et la requete de verification en fin de
-- fichier les liste.
--
-- NON COUVERT par ce lot, faute de donnees en amont : paladins (3 spes),
-- chamans (3 spes), soigneurs prêtre/druide, voleur Assassinat et Subtilite,
-- druide Ours. Guerrier Fureur vient du fichier 03 (guide Wowhead).

